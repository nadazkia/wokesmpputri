-- 1. EXTENSIONS
create extension if not exists "uuid-ossp";

-- 2. PROFILES & ADMIN ROLES
create table if not exists public.profiles (
  id uuid references auth.users on delete cascade primary key,
  email text not null,
  full_name text,
  role text not null check (role in ('admin', 'panitia', 'superadmin')) default 'panitia',
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

-- Trigger auto create profile on signup (hanya jika diinvite/dibuat di dashboard auth)
create or replace function public.handle_new_user()
returns trigger as $$
begin
  insert into public.profiles (id, email, full_name, role)
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data->>'full_name', 'Admin Wonderkind'),
    coalesce(new.raw_user_meta_data->>'role', 'panitia')
  )
  on conflict (id) do nothing;
  return new;
end;
$$ language plpgsql security definer;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Helper function: is_admin
create or replace function public.is_admin()
returns boolean as $$
begin
  return exists (
    select 1 from public.profiles
    where id = auth.uid()
    and role in ('admin', 'panitia', 'superadmin')
  );
end;
$$ language plpgsql security definer;

-- 3. PRODUCTS & VARIANTS
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text unique,
  description text,
  price integer not null default 0,
  img_name text,
  sizes text[] default array['Standard'],
  variations text[] default array['D1', 'D2', 'D3', 'D4'],
  variation_prices jsonb default '{}'::jsonb,
  variation_images jsonb default '{}'::jsonb,
  stock integer default 100,
  is_active boolean default true,
  sort_order integer default 0,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

-- 4. ORDERS & ORDER ITEMS
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  order_code text not null unique,
  buyer_name text not null,
  buyer_whatsapp text not null,
  unit text not null default 'DQ2 Putri',
  asrama text not null,
  kelas text not null,
  total_amount integer not null default 0,
  payment_status text not null check (payment_status in ('menunggu_verifikasi', 'lunas', 'dibatalkan')) default 'menunggu_verifikasi',
  order_status text not null check (order_status in ('pending', 'diproses', 'siap_diambil', 'selesai', 'dibatalkan')) default 'pending',
  payment_method text not null default 'manual_transfer',
  notes text,
  verified_at timestamptz,
  verified_by uuid references auth.users(id),
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  size text not null default 'Standard',
  variation text not null default 'D1',
  quantity integer not null check (quantity > 0),
  price integer not null check (price >= 0),
  subtotal integer not null check (subtotal >= 0),
  image_name text,
  created_at timestamptz default now()
);

-- Index order_code for fast lookups
create index if not exists idx_orders_order_code on public.orders(order_code);
create index if not exists idx_order_items_order_id on public.order_items(order_id);

